#pragma once
#include <string>

// Централизованная настройка TLS-сертификатов для всех HTTPS-запросов.
//
// Проблема, которую это решает: на Linux libcurl сам находит системное
// хранилище CA, а на Windows CA живут в реестре, и MinGW-сборка libcurl
// (на OpenSSL/Schannel) не знает, где их искать. В результате любой запрос
// к Mojang/Modrinth/Adoptium падает с "Problem with the SSL CA cert".
//
// Fallback-цепочка:
//   (a) CURLSSLOPT_NATIVE_CA — системное хранилище Windows (libcurl >= 7.71);
//   (b) cacert.pem рядом с .exe через CURLOPT_CAINFO;
//   (c) на Linux — поведение по умолчанию (системные CA находятся сами).
//
// Осознанно НЕ используется CURLOPT_SSL_VERIFYPEER=0 / VERIFYHOST=0:
// это отключает проверку сертификатов и является дырой в безопасности.

namespace curl_tls {

// Режим, который войдёт в силу для всех новых easy-хэндлов,
// а также причина ошибки (для логирования и текста ошибки в UI).
struct Result {
    bool native_ca_active;   // системное хранилище доступно и будет использоваться
    bool ca_info_active;     // cacert.pem найден и привязан через CURLOPT_CAINFO
    std::string error;       // ненулевой — если оба способа недоступны
};

// Инициализация libcurl: глобальный init + регистрация настройки TLS
// для всех последующих дескрипторов. Должна вызываться до любых запросов.
// На каждом этапе логирует: какая цепочка CAs фактически используется и
// любые проблемы. Возвращает сводку для отображения в UI, если нужно.
Result initialize();

// Применяет текущий TLS-режим к конкретному easy-хэндлу CURL*.
// Вызывается после curl_easy_init(). Никогда не отключает проверку
// сертификатов. Возвращает false, если ни один источник CAs не настроен —
// тогда запрос в любом случае упадёт, и это ошибка конфигурации.
bool apply(void* curl_easy_handle);

} // namespace curl_tls
